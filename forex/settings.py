# Database
# https://docs.djangoproject.com/en/6.0/ref/settings/#databases

def _database_from_url(url):
    """postgres://user:password@host:5432/dbname -> Django settings (no extra package needed)."""
    from urllib.parse import unquote, urlparse
    u = urlparse(url)
    return {
        'ENGINE': 'django.db.backends.postgresql',
        'NAME': u.path.lstrip('/'), 'USER': unquote(u.username or ''), 'PASSWORD': unquote(u.password or ''),
        'HOST': u.hostname or 'localhost', 'PORT': str(u.port or 5432), 'CONN_MAX_AGE': 60,
    }


if os.environ.get('DATABASE_URL', '').startswith(('postgres://', 'postgresql://')):
    DATABASES = {'default': _database_from_url(os.environ['DATABASE_URL'])}
